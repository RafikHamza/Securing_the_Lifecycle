from __future__ import annotations

import string
from pathlib import Path

from .model import BufferContract, Contract

HEADER_TEMPLATE = string.Template("""#ifndef ${guard}
#define ${guard}

#include <stddef.h>
#include <stdint.h>

${prototypes}

#endif /* ${guard} */
""")

IMPLEMENTATION_TEMPLATE = string.Template("""/* Generated by CPDVerifier.
 * This wrapper enforces the approved dispatch path declared in the
 * contract. Any confidentiality or integrity guarantee comes from the
 * declared transport sink implementation, not from generated code.
 */

#include "${header_name}"

#define CPD_VERIFIER_MAX_BUFFER 1024u

${transport_declarations}

static void cpd_verifier_copy_bytes(uint8_t *dst, const uint8_t *src, size_t length)
{
    size_t index;

    for (index = 0; index < length; ++index) {
        dst[index] = src[index];
    }
}

static void cpd_verifier_zeroize(uint8_t *buffer, size_t length)
{
    size_t index;

    for (index = 0; index < length; ++index) {
        buffer[index] = 0u;
    }
}

${wrappers}
""")

WRAPPER_TEMPLATE = string.Template("""int ${function_name}(${element_type} *raw_buffer, size_t length)
{
    const uint8_t *input_view;
    uint8_t dispatch_buffer[CPD_VERIFIER_MAX_BUFFER];
    int status;

    if (raw_buffer == NULL || length > CPD_VERIFIER_MAX_BUFFER) {
        return -1;
    }

    // [Formal Model] Allocated (caller) -> copied
    input_view = (const uint8_t *)raw_buffer;
    cpd_verifier_copy_bytes(dispatch_buffer, input_view, length);
${zeroize_caller}
    // [Formal Model] Temp buffer: Sent (via sink)
    status = ${transport_sink}(dispatch_buffer, length);

    // [Formal Model] Temp buffer: Sent -> Zeroized -> Unallocated
    cpd_verifier_zeroize(dispatch_buffer, length);

    return status;
}""")

MAKEFILE_TEMPLATE = string.Template("""# Generated by CPDVerifier
CPD_VERIFIER_OBJS += ${module}_cpd_verifier.o
""")

def generate_artifacts(contract: Contract, output_dir: str | Path) -> list[Path]:
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    header_name = f"{contract.module}_cpd_verifier.h"
    implementation_name = f"{contract.module}_cpd_verifier.c"
    makefile_name = f"{contract.module}_cpd_verifier.mk"

    written_files = [
        output_path / header_name,
        output_path / implementation_name,
        output_path / makefile_name,
    ]
    written_files[0].write_text(_render_header(contract), encoding="utf-8")
    written_files[1].write_text(
        _render_implementation(contract, header_name), encoding="utf-8"
    )
    written_files[2].write_text(MAKEFILE_TEMPLATE.substitute(module=contract.module), encoding="utf-8")
    return written_files


def _render_header(contract: Contract) -> str:
    guard = f"CPD_VERIFIER_{contract.module.upper()}_CPD_VERIFIER_H"
    prototypes = "\n".join(
        _render_prototype(buffer) for buffer in contract.sensitive_buffers
    )
    return HEADER_TEMPLATE.substitute(guard=guard, prototypes=prototypes)


def _render_implementation(contract: Contract, header_name: str) -> str:
    wrappers = "\n\n".join(
        _render_wrapper(buffer) for buffer in contract.sensitive_buffers
    )
    transport_declarations = _render_transport_declarations(contract)
    return IMPLEMENTATION_TEMPLATE.substitute(
        header_name=header_name,
        transport_declarations=transport_declarations,
        wrappers=wrappers
    )


def _render_transport_declarations(contract: Contract) -> str:
    declarations = []
    seen_sinks: set[str] = set()
    for buffer in contract.sensitive_buffers:
        if not buffer.transport_sink or buffer.transport_sink in seen_sinks:
            continue
        seen_sinks.add(buffer.transport_sink)
        declarations.append(
            f"int {buffer.transport_sink}(const uint8_t *data, size_t length);"
        )
    return "\n".join(declarations)


def _render_prototype(buffer: BufferContract) -> str:
    function_name = _wrapper_name(buffer)
    return f"int {function_name}({buffer.element_type} *raw_buffer, size_t length);"


def _render_wrapper(buffer: BufferContract) -> str:
    function_name = _wrapper_name(buffer)
    
    zeroize_caller = ""
    if buffer.must_zeroize:
        zeroize_caller = "    // [Formal Model] Caller buffer: Zeroized -> Unallocated\n"
        zeroize_caller += "    cpd_verifier_zeroize((uint8_t *)raw_buffer, length);\n"
        
    return WRAPPER_TEMPLATE.substitute(
        function_name=function_name,
        element_type=buffer.element_type,
        zeroize_caller=zeroize_caller,
        transport_sink=buffer.transport_sink
    )


def _wrapper_name(buffer: BufferContract) -> str:
    if buffer.allowed_sinks:
        return buffer.allowed_sinks[0]
    return f"cpd_verifier_send_{buffer.name}"
